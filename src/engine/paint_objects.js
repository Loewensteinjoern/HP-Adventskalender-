function flame(p, x, y, f, big) {
  const h = (big ? 7 : 5) + [0, 1, -1, 1][f % 4];
  const sway = [0, 1, 0, -1][f % 4];
  p.r(x - 1, y - h + 2, 3, h - 1, '#ff9a2a');
  p.r(x - 1 + sway, y - h, 2, 3, '#ffd36a');
  p.r(x, y - h + 3, 1, h - 3, '#fff2b0');
}
function bookRow(p, R, x0, x1, yBase, hMax) {
  const cols = ['#8a2a2a', '#2a4a8a', '#3a6a3a', '#8a6a2a', '#5a2a6a', '#2a6a6a', '#a0522d', '#d0b080', '#6a1e1e', '#e09a2c'];
  let x = x0;
  while (x < x1 - 2) {
    const w = 2 + ((R() * 3) | 0), h = hMax - ((R() * 5) | 0), c = cols[(R() * cols.length) | 0];
    if (x + w > x1) break;
    if (R() < 0.08 && x + 6 < x1) { // schräg liegendes Buch
      for (let i = 0; i < 5; i++) p.r(x + i, yBase - 3 - i, 3, 3, c);
      x += 7; continue;
    }
    p.r(x, yBase - h, w, h, c); p.r(x, yBase - h, 1, h, shade(c, 0.2)); p.r(x + w - 1, yBase - h, 1, h, shade(c, -0.3));
    if (R() < 0.5) p.r(x, yBase - h + 2, w, 1, '#e8c050');
    x += w + (R() < 0.15 ? 1 : 0);
  }
}

